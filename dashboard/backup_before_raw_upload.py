from pathlib import Path
import json
import joblib
import numpy as np
import pandas as pd
import matplotlib.pyplot as plt
import streamlit as st

# =========================================================
# 1. CONFIGURATION
# =========================================================
st.set_page_config(
    page_title="Satellite Health Monitoring System",
    page_icon="🛰️",
    layout="wide"
)

BASE_DIR = Path(__file__).resolve().parent.parent
DATA_DIR = BASE_DIR / "data"
RESULTS_DIR = BASE_DIR / "results"
MODEL_DIR_OPTIONS = [
    BASE_DIR / "models" / "8_features",
    BASE_DIR / "models" / "eight_features",
]
MODEL_DIR = next((p for p in MODEL_DIR_OPTIONS if p.exists()), MODEL_DIR_OPTIONS[0])

# The feature list is loaded from the artifact generated by the notebook.
FEATURE_LIST_PATH = MODEL_DIR / "feature_list.json"

@st.cache_data
def load_feature_list():
    with open(FEATURE_LIST_PATH, "r", encoding="utf-8") as f:
        features = json.load(f)
    if len(features) != 8:
        raise ValueError(f"Expected exactly 8 model features, found {len(features)}.")
    return features

FEATURES = load_feature_list()

# =========================================================
# 2. LOAD DATA AND MODEL ARTIFACTS
# =========================================================
@st.cache_data
def load_dataset():
    path = DATA_DIR / "raw" / "dataset.csv"
    return pd.read_csv(path) if path.exists() else pd.DataFrame()

@st.cache_data
def load_predictions():
    path = MODEL_DIR / "test_predictions_8_features.csv"
    return pd.read_csv(path) if path.exists() else pd.DataFrame()

@st.cache_data
def load_metrics():
    path = MODEL_DIR / "model_metrics_8_features.csv"
    return pd.read_csv(path) if path.exists() else pd.DataFrame()

@st.cache_data
def load_feature_importance():
    path = MODEL_DIR / "feature_importance_8_features.csv"
    return pd.read_csv(path) if path.exists() else pd.DataFrame()

@st.cache_resource
def load_models():
    ada = joblib.load(MODEL_DIR / "adaboost_8_features.joblib")
    iforest = joblib.load(MODEL_DIR / "isolation_forest_8_features.joblib")
    # The original training dataset has no missing values. Therefore the
    # median imputer made no changes during training and is not needed here.
    # Skipping it also avoids cross-version pickle incompatibility.
    scaler = joblib.load(MODEL_DIR / "scaler_8_features.joblib")
    return ada, iforest, scaler

dataset = load_dataset()
predictions = load_predictions()
metrics = load_metrics()
importance = load_feature_importance()

# =========================================================
# 3. HEADER
# =========================================================
st.title("🛰️ Satellite Health Monitoring System")
st.subheader("Machine Learning-Based Satellite Telemetry Anomaly Detection")
st.write(
    "Explore OPSSAT-AD test results and evaluate new segment-level telemetry "
    "features using the trained 8-feature machine learning models."
)
st.info(
    "This project detects anomalous telemetry segments. It does not diagnose "
    "the physical cause or identify a faulty satellite subsystem."
)
st.divider()

# =========================================================
# 4. SIDEBAR
# =========================================================
st.sidebar.title("Dashboard Controls")
model_choice = st.sidebar.selectbox(
    "Select model view",
    ["Both Models", "AdaBoost", "Isolation Forest"]
)
record_filter = st.sidebar.selectbox(
    "Filter test records",
    ["All Records", "Anomalies Only", "Normal Only"]
)

# =========================================================
# 5. VALIDATE AND PREPARE TEST PREDICTIONS
# =========================================================
st.header("📊 Satellite Health Overview")

if predictions.empty:
    st.error(
        "The 8-feature test predictions file was not found. "
        "Expected: models/8_features/test_predictions_8_features.csv"
    )
    st.stop()

required_prediction_columns = [
    "actual_anomaly",
    "adaboost_prediction",
    "iforest_prediction"
]
missing_prediction_columns = [
    c for c in required_prediction_columns if c not in predictions.columns
]
if missing_prediction_columns:
    st.error(f"Prediction file is missing columns: {missing_prediction_columns}")
    st.stop()

total_segments = len(predictions)
actual_anomalies = int(predictions["actual_anomaly"].sum())
actual_normal = total_segments - actual_anomalies
anomaly_rate = actual_anomalies / total_segments * 100 if total_segments else 0

m1, m2, m3, m4 = st.columns(4)
m1.metric("Test Segments", f"{total_segments:,}")
m2.metric("Actual Anomalies", f"{actual_anomalies:,}")
m3.metric("Actual Normal Segments", f"{actual_normal:,}")
m4.metric("Actual Anomaly Rate", f"{anomaly_rate:.1f}%")

# =========================================================
# 6. MODEL DETECTION SUMMARY
# =========================================================
st.divider()
st.header("🤖 Model Detection Summary")

ada_detected = int(predictions["adaboost_prediction"].sum())
if_detected = int(predictions["iforest_prediction"].sum())

c1, c2 = st.columns(2)
with c1:
    st.subheader("AdaBoost — 8 features")
    st.metric("Predicted Anomalies", ada_detected)
    st.metric("Predicted Normal", total_segments - ada_detected)
with c2:
    st.subheader("Isolation Forest — 8 features")
    st.metric("Predicted Anomalies", if_detected)
    st.metric("Predicted Normal", total_segments - if_detected)

# =========================================================
# 7. MODEL PERFORMANCE
# =========================================================
st.divider()
st.header("📈 Model Performance Comparison")

if not metrics.empty:
    st.dataframe(metrics, use_container_width=True, hide_index=True)

    metric_columns = [
        c for c in ["Accuracy", "Precision", "Recall", "F1-score", "ROC-AUC", "F1"]
        if c in metrics.columns
    ]
    # Avoid duplicate metric names and use a grouped chart so each model's
    # metric values can be compared side by side (rather than stacked).
    metric_columns = list(dict.fromkeys(metric_columns))
    if metric_columns:
        model_col = "Model" if "Model" in metrics.columns else metrics.columns[0]
        chart_data = metrics.set_index(model_col)[metric_columns].apply(
            pd.to_numeric, errors="coerce"
        )
        chart_data = chart_data.dropna(how="all").fillna(0)

        fig, ax = plt.subplots(figsize=(10, 5))
        x = np.arange(len(chart_data.index))
        bar_width = 0.8 / max(len(metric_columns), 1)
        for metric_index, metric_name in enumerate(metric_columns):
            offsets = x - 0.4 + bar_width / 2 + metric_index * bar_width
            bars = ax.bar(
                offsets,
                chart_data[metric_name].to_numpy(dtype=float),
                width=bar_width,
                label=metric_name
            )
            ax.bar_label(bars, fmt="%.2f", fontsize=8, padding=2)

        ax.set_title("Model Metrics — Side-by-Side Comparison")
        ax.set_ylabel("Score")
        ax.set_xlabel("Machine Learning Model")
        ax.set_xticks(x)
        ax.set_xticklabels([str(label) for label in chart_data.index], rotation=0)
        ax.set_ylim(0, 1.12)
        ax.grid(axis="y", alpha=0.25)
        ax.set_axisbelow(True)
        ax.legend(title="Evaluation Metric", ncols=min(3, len(metric_columns)))
        fig.tight_layout()
        st.pyplot(fig, use_container_width=True)
        plt.close(fig)
else:
    st.warning("8-feature model metrics file not found.")

if not importance.empty and {"Feature", "Importance"}.issubset(importance.columns):
    st.subheader("AdaBoost Feature Importance")
    importance_sorted = importance.sort_values("Importance", ascending=True)
    fig, ax = plt.subplots(figsize=(8, 4.5))
    ax.barh(importance_sorted["Feature"], importance_sorted["Importance"])
    ax.set_xlabel("Importance")
    ax.set_title("Importance of the 8 selected features")
    ax.grid(axis="x", alpha=0.25)
    plt.tight_layout()
    st.pyplot(fig)
    plt.close(fig)

st.caption(
    "The current 8-feature AdaBoost experiment reported approximately 91.1% "
    "accuracy, 81.1% precision, 76.1% recall, 78.5% F1-score and 0.931 ROC-AUC. "
    "The table above is loaded from your actual saved metrics file."
)

# =========================================================
# 8. ANOMALY DISTRIBUTION AND CHANNEL ANALYSIS
# =========================================================
st.divider()
st.header("🔍 Test Set Anomaly Distribution")

left, right = st.columns(2)
with left:
    st.subheader("Actual labels")
    actual_counts = predictions["actual_anomaly"].value_counts().reindex([0, 1], fill_value=0)
    st.bar_chart(pd.DataFrame({
        "Segments": actual_counts.values
    }, index=["Normal", "Anomaly"]))
with right:
    st.subheader("Predicted anomalies")
    st.bar_chart(pd.DataFrame({
        "Predicted anomalies": [ada_detected, if_detected]
    }, index=["AdaBoost", "Isolation Forest"]))

if "channel" in predictions.columns:
    st.subheader("📡 Channel-Level Analysis")
    channel_measure = st.selectbox(
        "Choose channel measurement",
        ["actual_anomaly", "adaboost_prediction", "iforest_prediction"],
        format_func=lambda x: {
            "actual_anomaly": "Actual anomalies",
            "adaboost_prediction": "AdaBoost predicted anomalies",
            "iforest_prediction": "Isolation Forest predicted anomalies"
        }[x]
    )
    channel_counts = (
        predictions.groupby("channel")[channel_measure]
        .sum().sort_values(ascending=False)
    )
    st.bar_chart(channel_counts)

# =========================================================
# 9. TEST PREDICTION RECORDS
# =========================================================
st.divider()
st.header("📋 Existing Test Prediction Records")

filtered = predictions.copy()
if record_filter == "Anomalies Only":
    filtered = filtered[filtered["actual_anomaly"] == 1]
elif record_filter == "Normal Only":
    filtered = filtered[filtered["actual_anomaly"] == 0]

if model_choice == "AdaBoost":
    wanted = [
        "segment", "channel", "actual_anomaly",
        "adaboost_prediction", "adaboost_anomaly_score"
    ]
elif model_choice == "Isolation Forest":
    wanted = [
        "segment", "channel", "actual_anomaly",
        "iforest_prediction", "iforest_anomaly_score"
    ]
else:
    wanted = filtered.columns.tolist()

display_columns = [c for c in wanted if c in filtered.columns]
st.write(f"Showing {len(filtered):,} records")
st.dataframe(filtered[display_columns], use_container_width=True, hide_index=True)
st.download_button(
    "⬇️ Download 8-feature test predictions",
    data=filtered.to_csv(index=False),
    file_name="satellite_test_predictions_8_features.csv",
    mime="text/csv"
)

# =========================================================
# 10. NEW TELEMETRY ANOMALY DETECTION
# =========================================================
st.divider()
st.header("🛰️ Test New Satellite Telemetry")
st.write(
    "Enter eight engineered feature values manually or upload a CSV containing "
    "the same eight features. The saved models are used without retraining."
)
st.warning(
    "These are engineered segment-level features, not raw sensor readings. "
    "A CSV of timestamp/value telemetry cannot be used directly; it must first "
    "be processed into these same eight OPSSAT-AD features."
)

try:
    adaboost, iforest, scaler = load_models()

    if input_method := st.radio(
        "Choose input method",
        ["Manual Entry", "Upload CSV"],
        horizontal=True
    ):
        input_df = None

        # ------------------ MANUAL ENTRY ------------------
        if input_method == "Manual Entry":
            st.subheader("Enter the 8 feature values")

            if not dataset.empty:
                defaults = dataset[FEATURES].median(numeric_only=True)
            else:
                defaults = pd.Series(0.0, index=FEATURES)

            with st.form("eight_feature_input_form"):
                values = {}
                cols = st.columns(2)
                for i, feature in enumerate(FEATURES):
                    default_value = defaults.get(feature, 0.0)
                    if pd.isna(default_value) or not np.isfinite(default_value):
                        default_value = 0.0
                    with cols[i % 2]:
                        values[feature] = st.number_input(
                            feature,
                            value=float(default_value),
                            format="%.8f",
                            key=f"manual_{feature}"
                        )
                submitted = st.form_submit_button(
                    "🔍 Detect Anomaly",
                    use_container_width=True
                )
            if submitted:
                input_df = pd.DataFrame([values], columns=FEATURES)

        # ------------------ CSV UPLOAD ------------------
        else:
            st.subheader("Upload an 8-feature CSV")
            uploaded_file = st.file_uploader(
                "Choose CSV file",
                type=["csv"],
                key="eight_feature_csv"
            )
            if uploaded_file is not None:
                uploaded_df = pd.read_csv(uploaded_file)
                missing = [f for f in FEATURES if f not in uploaded_df.columns]
                if missing:
                    st.error("CSV is missing required columns: " + ", ".join(missing))
                elif uploaded_df.empty:
                    st.warning("The uploaded CSV contains no rows.")
                else:
                    st.success(f"Loaded {len(uploaded_df)} rows.")
                    st.dataframe(uploaded_df[FEATURES].head(), use_container_width=True)
                    if st.button("🔍 Detect Anomalies", use_container_width=True):
                        input_df = uploaded_df[FEATURES].copy()

        # ------------------ PREDICTION ------------------
        if input_df is not None:
            numeric_input = input_df[FEATURES].apply(pd.to_numeric, errors="coerce")

            if numeric_input.isna().any().any():
                st.error("Some feature values are missing or non-numeric. Please correct them.")
            elif not np.isfinite(numeric_input.to_numpy(dtype=float)).all():
                st.error("Infinite or invalid values were found.")
            else:
                # The OPSSAT-AD training dataset contains no missing values.
                # The saved imputer was therefore an identity step for training
                # data, so apply the saved scaler directly to complete inputs.
                scaled_input = scaler.transform(numeric_input)

                ada_pred = adaboost.predict(scaled_input).astype(int)
                ada_probabilities = adaboost.predict_proba(scaled_input)
                anomaly_class_index = list(adaboost.classes_).index(1)
                ada_scores = ada_probabilities[:, anomaly_class_index]

                if_raw = iforest.predict(scaled_input)
                if_pred = np.where(if_raw == -1, 1, 0).astype(int)
                if_scores = -iforest.score_samples(scaled_input)

                results = numeric_input.copy()
                results.insert(0, "Telemetry Segment", np.arange(1, len(results) + 1))
                results["AdaBoost Prediction"] = np.where(ada_pred == 1, "ANOMALY", "NORMAL")
                results["AdaBoost Anomaly Probability"] = ada_scores
                results["Isolation Forest Prediction"] = np.where(if_pred == 1, "ANOMALY", "NORMAL")
                results["Isolation Forest Anomaly Score"] = if_scores

                st.divider()
                st.subheader("🎯 Prediction Results")
                total = len(results)
                ca, ci, cn = st.columns(3)
                ca.metric("Segments Tested", total)
                ci.metric("AdaBoost Anomalies", int(ada_pred.sum()))
                cn.metric("Isolation Forest Anomalies", int(if_pred.sum()))

                for idx, row in results.iterrows():
                    with st.expander(
                        f"Telemetry Segment {int(row['Telemetry Segment'])}",
                        expanded=(total == 1)
                    ):
                        a, b = st.columns(2)
                        with a:
                            st.markdown("#### AdaBoost")
                            if row["AdaBoost Prediction"] == "ANOMALY":
                                st.error("🚨 ANOMALY DETECTED")
                            else:
                                st.success("✅ NORMAL")
                            st.metric("Anomaly probability", f"{row['AdaBoost Anomaly Probability']:.2%}")
                        with b:
                            st.markdown("#### Isolation Forest")
                            if row["Isolation Forest Prediction"] == "ANOMALY":
                                st.error("🚨 ANOMALY DETECTED")
                            else:
                                st.success("✅ NORMAL")
                            st.metric("Anomaly score", f"{row['Isolation Forest Anomaly Score']:.5f}")

                        if ada_pred[idx] == 1 and if_pred[idx] == 1:
                            st.error("Both models detected an anomaly.")
                        elif ada_pred[idx] != if_pred[idx]:
                            st.warning("The models disagree. Further investigation is recommended.")
                        else:
                            st.success("Both models agree on this prediction.")

                st.subheader("Detailed prediction table")
                st.dataframe(results, use_container_width=True, hide_index=True)
                st.download_button(
                    "⬇️ Download new telemetry predictions",
                    data=results.to_csv(index=False),
                    file_name="new_telemetry_predictions_8_features.csv",
                    mime="text/csv"
                )

except FileNotFoundError as error:
    st.error(f"Required 8-feature model artifact not found: {error}")
    st.info("Check that the models/8_features folder contains all model and preprocessing files.")
except Exception as error:
    st.error(f"Prediction system error: {error}")

